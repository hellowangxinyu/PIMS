# 读取现有 riddles.js
src = open(P, encoding='utf-8').read()
pairs = re.findall(r"\{ q: '([^']+)', a: '([^']+)' \}", src)
print('riddles found:', len(pairs))
assert len(pairs) == 100

# 生成带 d 的新文件
lines = ['// 100 道脑筋急转弯（对话气泡表演用），d 为每题 4 个"沾边"错误答案']
for q, a in pairs:
    d = DIST.get(q)
    assert d, 'missing distractors: ' + q
    assert len(d) == 4, q
    dstr = ', '.join("'%s'" % x for x in d)
    lines.append("  { q: '%s', a: '%s', d: [%s] }," % (q, a, dstr))

out = 'export const RIDDLES = [\n' + '\n'.join(lines) + '\n]\n'
open(P, 'w', encoding='utf-8').write(out)
print('rewritten, lines:', len(lines))
